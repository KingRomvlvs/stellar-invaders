// Get sprite dimensions
export function getSpriteSize(sprite: number[][]): { width: number; height: number } {
  return {
    width: sprite[0]?.length ?? 0,
    height: sprite.length,
  }
}

// Get invader sprite dimensions
export function getInvaderSpriteSize(type: InvaderType): { width: number; height: number } {
  const sprite = INVADER_SPRITES[type][0]
  return getSpriteSize(sprite)
}
